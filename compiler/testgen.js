// Automatic test generation. Reads the checked AST and writes plain Cluub tests
// (readable by QA) for models, services, apis and pages:
//   - every model rule (required, min, max, one of, email) gets a passing and a failing case
//   - every `require` in a service action gets a test that breaks it on purpose
//   - every api route gets input-validation tests
//   - every page is rendered, and every button is clicked, against a real in-memory backend
import { msg } from '../runtime/messages.js';
import { sampleValue } from '../runtime/core.js';
import { routeParams, pathParams } from './checker.js';

const HEADER = '# Generated by Cluub from your code. Do not edit: this file is rewritten on every `cluub test`.\n# Write your own tests in tests/*.test.clb\n\n';

export function lit(v) {
  if (v === null || v === undefined) return 'nothing';
  if (typeof v === 'string') return '"' + v.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\{/g, '\\{').replace(/\}/g, '\\}').replace(/\n/g, '\\n') + '"';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) return `[${v.map(lit).join(', ')}]`;
  return `{${Object.entries(v).map(([k, x]) => `${k}: ${lit(x)}`).join(', ')}}`;
}

function evalLit(e) {
  if (!e) return undefined;
  switch (e.kind) {
    case 'Num': return e.value;
    case 'Bool': return e.value;
    case 'Nothing': return null;
    case 'Str': return e.parts.every((p) => p.text !== undefined) ? e.parts.map((p) => p.text).join('') : undefined;
    case 'Unary': return e.op === '-' && e.expr.kind === 'Num' ? -e.expr.value : undefined;
    case 'List': { const a = e.items.map(evalLit); return a.includes(undefined) ? undefined : a; }
  }
  return undefined;
}

// AST field -> runtime-like field description
function fieldInfo(f) {
  const info = { name: f.name, type: f.type, required: false };
  for (const c of f.constraints) {
    if (c.name === 'required') info.required = true;
    else info[c.name] = evalLit(c.value);
    if (c.message) info[`${c.name}Message`] = evalLit(c.message);
  }
  return info;
}

function modelsMap(decls) {
  const map = {};
  for (const d of decls.filter((x) => x.kind === 'Model')) {
    map[d.name] = { def: { name: d.name, fields: d.fields.map(fieldInfo) } };
    map[d.name].sample = () => ({ toJSON: () => Object.fromEntries(map[d.name].def.fields.map((f) => [f.name, sampleValue(f, map)])) });
  }
  return map;
}

function sampleFor(type, models, name = 'value') { return sampleValue({ name, type: type || { name: 'text' } }, models); }

function modelTests(d, models) {
  const fields = d.fields.map(fieldInfo);
  const valid = Object.fromEntries(fields.map((f) => [f.name, sampleValue(f, models)]));
  const call = (over) => `${d.name}(${fields.map((f) => `${f.name}: ${lit(f.name in over ? over[f.name] : valid[f.name])}`).join(', ')})`;
  let out = `test "${d.name}: can be created with valid values"\n  let item = ${call({})}\n`;
  const first = fields.find((f) => typeof valid[f.name] !== 'object');
  if (first) out += `  expect item.${first.name} is ${lit(valid[first.name])}\n`;
  out += '\n';
  for (const f of fields) {
    const cases = [];
    const tn = f.type.name;
    const textLike = ['text', 'email', 'url', 'id'].includes(tn);
    if (f.required && (textLike || tn === 'date')) cases.push(['is required', '', f.requiredMessage || msg.required(f.name)]);
    if (f.required && tn === 'list') cases.push(['is required', [], f.requiredMessage || msg.required(f.name)]);
    if (tn === 'email') cases.push(['must be a valid email', 'not-an-email', msg.email(f.name)]);
    if (typeof f.min === 'number') {
      if (textLike && f.min > 1) cases.push([`must be at least ${f.min} characters`, 'x'.repeat(f.min - 1), f.minMessage || msg.minText(f.name, f.min)]);
      if (tn === 'number') cases.push([`must be at least ${f.min}`, f.min - 1, f.minMessage || msg.minNumber(f.name, f.min)]);
    }
    if (typeof f.max === 'number') {
      if (textLike) cases.push([`must be at most ${f.max} characters`, 'x'.repeat(f.max + 1), f.maxMessage || msg.maxText(f.name, f.max)]);
      if (tn === 'number') cases.push([`must be at most ${f.max}`, f.max + 1, f.maxMessage || msg.maxNumber(f.name, f.max)]);
    }
    if (Array.isArray(f.oneOf) && typeof f.oneOf[0] === 'string') cases.push([`must be one of the allowed values`, 'not-a-valid-option', f.oneOfMessage || msg.oneOf(f.name, f.oneOf)]);
    for (const [title, bad, message] of cases)
      out += `test "${d.name}: ${f.name} ${title}"\n  expect ${call({ [f.name]: bad })} fails with ${lit(message)}\n\n`;
  }
  return out;
}

// Turn `require <cond>, "message"` into an input that breaks it.
function breakRequire(cond, params, models) {
  const P = (n) => params.find((p) => p.name === n);
  let neg = false;
  if (cond.kind === 'Unary' && cond.op === 'not') { neg = true; cond = cond.expr; }
  if (cond.kind === 'IsEmpty' && neg && cond.expr.kind === 'Name' && P(cond.expr.name)) {
    const p = P(cond.expr.name);
    return { [p.name]: p.type?.name === 'list' ? [] : '' };
  }
  if (cond.kind === 'Binary' && cond.op === 'is' && neg && cond.left.kind === 'Name' && cond.right.kind === 'Nothing' && P(cond.left.name)) return { [cond.left.name]: null };
  if (cond.kind === 'Binary' && !neg && ['>', '>=', '<', '<='].includes(cond.op)) {
    const n = evalLit(cond.right);
    if (typeof n !== 'number') return null;
    const bad = { '>': n, '>=': n - 1, '<': n, '<=': n + 1 }[cond.op];
    if (cond.left.kind === 'Name' && P(cond.left.name)?.type?.name === 'number') return { [cond.left.name]: bad };
    if (cond.left.kind === 'Member' && cond.left.prop === 'count' && cond.left.obj.kind === 'Name' && P(cond.left.obj.name) && bad >= 0) {
      const p = P(cond.left.obj.name);
      return { [p.name]: p.type?.name === 'list' ? Array(bad).fill(sampleFor(p.type.of, models)) : 'x'.repeat(bad) };
    }
  }
  return null;
}

function usesStoreLookup(body) {
  const s = JSON.stringify(body, (k, v) => (k === 'ref' ? (v?.kind === 'dep' ? { dep: v.decl.kind } : undefined) : k === 'decl' || k === 'action' ? undefined : v));
  return /"prop":"(get|update|remove)"/.test(s) || /"kind":"Fail"/.test(s) || /"dep":"Client"/.test(s);
}

function serviceTests(d, models) {
  let out = '';
  for (const a of d.actions) {
    const valid = Object.fromEntries(a.params.map((p) => [p.name, p.default ? undefined : sampleFor(p.type, models, p.name)]));
    const call = (over) => `${d.name}.${a.name}(${a.params.filter((p) => over[p.name] !== undefined || valid[p.name] !== undefined).map((p) => `${p.name}: ${lit(p.name in over ? over[p.name] : valid[p.name])}`).join(', ')})`;
    for (const s of a.body) {
      if (s.kind !== 'Require') break;
      const bad = breakRequire(s.cond, a.params, models);
      if (!bad) continue;
      const m = evalLit(s.message);
      out += `test "${d.name}.${a.name}: rejects ${Object.entries(bad).map(([k, v]) => `${k} = ${lit(v).replace(/"/g, "'")}`).join(', ')}"\n  expect ${call(bad)} fails${m ? ` with ${lit(m)}` : ''}\n\n`;
    }
    if (!usesStoreLookup(a.body)) out += `test "${d.name}.${a.name}: works with valid input"\n` + (a.returns ? `  let result = ${call({})}\n  expect result is not nothing\n\n` : `  ${call({})}\n\n`);
  }
  return out;
}

function apiTests(d, models) {
  let out = '';
  for (const r of d.routes) {
    const ps = r.allParams || routeParams(r, d.baseText);
    const path = (d.baseText.replace(/\/$/, '') + '/' + r.pathText.replace(/^\//, '')).replace(/\/$/, '').replace(/\{(\w+)\}/g, '1') || '/';
    const inputs = ps.filter((p) => p.from !== 'path');
    const valid = Object.fromEntries(inputs.map((p) => [p.name, sampleFor(p.type, models, p.name)]));
    const send = (obj) => {
      if (r.method === 'GET' || r.method === 'DELETE') {
        const q = Object.entries(obj).map(([k, v]) => `${k}=${encodeURIComponent(typeof v === 'object' ? JSON.stringify(v) : v)}`).join('&');
        return `request ${r.method.toLowerCase()} ${lit(path + (q ? '?' + q : ''))}`;
      }
      return `request ${r.method.toLowerCase()} ${lit(path)} with ${lit(obj)}`;
    };
    for (const p of inputs.filter((x) => !x.default && !x.type?.optional)) {
      const without = { ...valid }; delete without[p.name];
      out += `test "${d.name}.${r.name}: says when ${p.name} is missing"\n  let response = ${send(without)}\n  expect response.status is 400\n  expect response.body.error.message has ${lit(p.name)}\n\n`;
    }
    for (const p of inputs.filter((x) => x.type?.name === 'number')) {
      out += `test "${d.name}.${r.name}: rejects text where ${p.name} should be a number"\n  let response = ${send({ ...valid, [p.name]: 'abc' })}\n  expect response.status is 400\n\n`;
    }
    if (r.method === 'GET' && !ps.length) out += `test "${d.name}.${r.name}: responds"\n  let response = ${send({})}\n  expect response.status is 200\n\n`;
  }
  return out;
}

function pageTests(d, decls) {
  if (pathParams(d.pathText).length || !d.view) return '';
  const texts = [], buttons = [], inputs = [];
  const walk = (nodes) => {
    for (const n of nodes) {
      if (n.kind !== 'El') continue; // skip if/for/components: their content depends on data
      const s = evalLit(n.arg);
      if (typeof s === 'string' && s.trim() && ['heading', 'subheading', 'text', 'label'].includes(n.tag)) texts.push(s);
      if (n.tag === 'button' && typeof s === 'string' && s.trim() && !n.props.some((p) => p.name === 'disabled')) buttons.push(s);
      if (n.tag === 'input') { const ph = evalLit(n.props.find((p) => p.name === 'placeholder')?.value); const ty = evalLit(n.props.find((p) => p.name === 'type')?.value); if (typeof ph === 'string' && ph && ty !== 'number') inputs.push(ph); }
      walk(n.children);
    }
  };
  walk(d.view);
  const checks = texts.slice(0, 2).map((t) => `  expect screen has ${lit(t)}\n`).join('');
  let out = `test "${d.name} page: renders"\n  render ${d.name}\n${checks || '  expect screen is not nothing\n'}\n`;
  for (const b of [...new Set(buttons)]) {
    // Clicking may navigate to another page, so only require that nothing crashed
    // (a crash fails the test automatically).
    out += `test "${d.name} page: the ${b.replace(/"/g, "'")} button works"\n  render ${d.name}\n${inputs.map((i) => `  type "Sample text" into ${lit(i)}\n`).join('')}  click ${lit(b)}\n  expect screen is not nothing\n\n`;
  }

  return out;
}

export function generateTests(decls) {
  const models = modelsMap(decls);
  const files = {};
  const add = (name, body) => { if (body.trim()) files[`tests/generated/${name}.test.clb`] = HEADER + body.trimEnd() + '\n'; };
  add('models', decls.filter((d) => d.kind === 'Model').map((d) => modelTests(d, models)).join(''));
  add('services', decls.filter((d) => d.kind === 'Service').map((d) => serviceTests(d, models)).join(''));
  add('api', decls.filter((d) => d.kind === 'Api').map((d) => apiTests(d, models)).join(''));
  add('ui', decls.filter((d) => d.kind === 'Page').map((d) => pageTests(d, decls)).join(''));
  return files;
}
